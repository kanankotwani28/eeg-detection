"""Generate REPORT.md from artifacts/results (never from hand-typed numbers). `make report`."""
from __future__ import annotations

import json

import numpy as np
import pandas as pd

from src.report.figures import main_results, privacy_utility
from src.utils.paths import RESULTS, ROOT


def _f(x, nd=3):
    return "—" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


def _ci(row, m):
    return f"{_f(row.get(m))} [{_f(row.get(m + '_lo'))}, {_f(row.get(m + '_hi'))}]"


def md_table(df: pd.DataFrame) -> str:
    if df.empty:
        return "_no results_\n"
    cols = list(df.columns)
    out = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    for _, r in df.iterrows():
        out += "| " + " | ".join(str(r[c]) for c in cols) + " |\n"
    return out


def _read(name):
    p = RESULTS / name
    return pd.read_parquet(p) if p.exists() else pd.DataFrame()


def cohort_table(c: dict) -> pd.DataFrame:
    rows = []
    for t in ("T1", "T2"):
        for cls, v in c.get(t, {}).items():
            rows.append({"task": t, "class": cls, "n": v["n"], "age mean (SD)": f"{_f(v['age_mean'], 1)} ({_f(v['age_sd'], 1)})",
                         "sex (raw codes)": ", ".join(f"{k}: {n}" for k, n in v["sex_raw_counts"].items()),
                         "comorbid": v["comorbid"]})
    return pd.DataFrame(rows)


def results_table(s: pd.DataFrame) -> pd.DataFrame:
    if s.empty:
        return s
    rows = []
    for _, r in s.sort_values(["experiment", "variant", "model", "eps"]).iterrows():
        rows.append({"exp": r["experiment"], "variant": r["variant"], "model": r["model"], "regime": r["regime"],
                     "task": r["task"], "ε": r["eps"], "n": int(r["n_participants"]),
                     "BA [95% CI]": _ci(r, "balanced_accuracy"), "AUC [95% CI]": _ci(r, "auc"),
                     "BA mean±SD (folds×seeds)": f"{_f(r.get('balanced_accuracy_mean'))} ± {_f(r.get('balanced_accuracy_sd'))}",
                     "worst client BA": _f(r.get("worst_balanced_accuracy"))})
    return pd.DataFrame(rows)


def write_report() -> str:
    s = _read("summary_table.parquet")
    meta = json.loads((RESULTS / "summary.json").read_text()) if (RESULTS / "summary.json").exists() else {}
    cohort = json.loads((RESULTS / "cohort.json").read_text()) if (RESULTS / "cohort.json").exists() else {}
    qc = json.loads((RESULTS / "qc.json").read_text()) if (RESULTS / "qc.json").exists() else {}
    comps, lira, ext = _read("comparisons.parquet"), _read("lira.parquet"), _read("external.parquet")
    pu, mr = privacy_utility(s) if not s.empty else None, main_results(s) if not s.empty else None
    L = ["# REPORT — Federated, participant-level DP EEG classification of MDD on TDBRAIN", ""]
    L.append("_Auto-generated by `make report` from the logged MLflow runs (src/report/tables.py). "
             "Do not edit by hand._\n")
    if meta.get("synthetic"):
        L.append("> **SYNTHETIC DATA.** These numbers come from generated test data (src/data/synthetic.py) and say "
                 "nothing about TDBRAIN, Mumtaz or depression.\n")
    L.append("> **Research benchmark, not a diagnostic tool.** No model or EEG feature here is a clinical test or a "
             "biomarker of depression.\n")
    L.append("## 1. Cohort\n")
    fc = cohort.get("flowchart", {})
    if fc:
        L.append(f"Participants {fc.get('participants')} → first session {fc.get('first_session')} → with restEC "
                 f"{fc.get('with_restEC')} → labelled (not blinded/UNKNOWN) {fc.get('labelled_not_blinded')} → "
                 f"T1 {fc.get('T1_final')}, T2 {fc.get('T2_final')}. Rules: {cohort.get('cohort_rules')}.\n")
    L.append(md_table(cohort_table(cohort)))
    if qc:
        L.append(f"\nQC: {qc['n_excluded']}/{qc['n_participants']} participants excluded "
                 f"({100 * qc['excluded_fraction']:.1f}%), epoch rejection {100 * qc['epoch_rejection_rate']:.1f}%, "
                 f"{qc['n_recordings_with_interpolation']} recordings with within-recording interpolation "
                 f"({qc['n_channels_interpolated_total']} channels). Eyes-closed alpha O1/O2 > Fp1/Fp2 in "
                 f"{100 * qc['psd_check']['fraction_EC_alpha_O_gt_Fp']:.0f}% of participants.\n")
    L.append("## 2. Main results (participant-level, out-of-fold, seed-averaged; 2,000-resample bootstrap CIs)\n")
    if mr:
        L.append(f"![main results]({mr.relative_to(ROOT)})\n")
    L.append(md_table(results_table(s)))
    L.append("\nE01 (shuffled labels) must be ≈ 0.5. E12 is a DELIBERATELY WRONG segment-level split and only shows "
             "how much leakage inflates scores.\n")
    L.append("### Paired comparisons (A − B on common participants; paired bootstrap 95% CI; no p-values)\n")
    if not comps.empty:
        c = comps.copy()
        c["A − B [95% CI]"] = c.apply(lambda r: f"{_f(r['diff'])} [{_f(r['lo'])}, {_f(r['hi'])}]", axis=1)
        L.append(md_table(c[["comparison", "metric", "A − B [95% CI]", "n_participants"]]))
    L.append("## 3. Privacy\n")
    L.append("Threat model: an honest-but-curious server, or anyone with query access to the released model, tries "
             "to infer whether a participant was in training. The privacy unit is the **participant**: ε is the "
             "participant-level guarantee for each client's released updates (max over clients). The epoch-level ε "
             "is shown only for comparison; it is what a per-sample accountant would report and is **not** a "
             "participant guarantee.\n")
    if pu:
        L.append(f"![privacy-utility]({pu.relative_to(ROOT)})\n")
    d = s[s["experiment"] == "E09"] if not s.empty else s
    if not d.empty:
        t = d[["model", "eps", "n_participants"]].copy()
        t["BA [95% CI]"] = d.apply(lambda r: _ci(r, "balanced_accuracy"), axis=1)
        t["AUC [95% CI]"] = d.apply(lambda r: _ci(r, "auc"), axis=1)
        t["achieved participant ε (mean)"] = d.get("epsilon_mean", pd.Series(index=d.index, dtype=float)).map(_f)
        t["epoch-level ε (reference only)"] = d.get("epsilon_epoch_level_reference_mean",
                                                   pd.Series(index=d.index, dtype=float)).map(_f)
        L.append(md_table(t))
    L.append("\n### LiRA membership-inference audit (participant level)\n")
    if not lira.empty:
        cols = [c for c in ["model", "regime", "eps", "achieved_epsilon", "auc", "tpr_at_fpr_0.01", "tpr_at_fpr_0.05",
                            "tpr_at_fpr_0.001", "n_nonmember_evals", "sanity_auc_nonmembers_only", "n_models"] if c in lira]
        L.append(md_table(lira[cols].map(lambda v: _f(v) if isinstance(v, float) else v)))
        if "tpr_at_fpr_0.001_note" in lira and lira["tpr_at_fpr_0.001_note"].notna().any():
            L.append(f"\nTPR at 0.1% FPR: {lira['tpr_at_fpr_0.001_note'].dropna().iloc[0]}.\n")
    L.append("## 4. External test (TDBRAIN → Mumtaz, frozen models, evaluated once)\n")
    if not ext.empty:
        e = ext[ext["kind"] == "external"]
        if not e.empty:
            t = e[["source"]].copy()
            for m in ("balanced_accuracy", "auc", "sensitivity", "specificity"):
                t[m + " [95% CI]"] = e.apply(lambda r, m=m: _ci(r, m), axis=1)
            t["n"] = e.get("n", pd.Series(index=e.index)).map(lambda v: int(v) if pd.notna(v) else "—")
            L.append(md_table(t))
        p = ext[ext["kind"] == "probe"]
        if not p.empty:
            r = p.iloc[0]
            L.append(f"\nE13 dataset-identity probe (TDBRAIN-HC vs Mumtaz-HC): AUC {_ci(r, 'auc')}. A high AUC means "
                     "the datasets are separable from band power alone, so pooled training risks shortcut learning.\n")
        mcv = ext[ext["kind"] == "mumtaz_cv"]
        if not mcv.empty:
            L.append("\nE20 within-Mumtaz CV:\n")
            L.append(md_table(mcv[["model", "mode", "participant_ba", "participant_auc", "segment_ba"]].map(
                lambda v: _f(v) if isinstance(v, float) else v)))
    L.append("## 5. Limitations\n")
    L += ["- Simulated clients are random partitions of one archive, **not hospitals**; real sites differ in hardware, "
          "protocol and population.",
          "- The external set (Mumtaz) is small; its CIs are wide.",
          "- Medication was not systematically tracked in TDBRAIN and alters the EEG spectrum.",
          "- Diagnostic labels are noisy (clinical-practice indications; comorbidity).",
          "- Results on subject-level splits only; segment-level numbers (E12) are a leakage demonstration.",
          "- **Not a diagnostic tool.** Explainability outputs explain the model, not the disorder.", ""]
    L.append("## 6. Reproducibility\n")
    L.append(f"git commit `{meta.get('git_commit')}`, split hash `{meta.get('split_sha256')}`, participants.tsv hash "
             f"`{meta.get('participants_tsv_hashes')}`, seeds {meta.get('seeds')}, {meta.get('n_runs')} MLflow runs. "
             f"Packages: {meta.get('packages')}.\n")
    text = "\n".join(L)
    (ROOT / "REPORT.md").write_text(text)
    return text


if __name__ == "__main__":
    write_report()
    print("Wrote REPORT.md")
